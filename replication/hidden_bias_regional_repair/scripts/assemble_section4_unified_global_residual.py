#!/usr/bin/env python3
"""Generate Section 4 tables from the unified global-residual reconstruction."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


METHODS = (
    ("aipw", "AIPW", "Aipw"),
    ("tmle", "fixed-floor TMLE", "Tmle"),
    ("ctmle", "C-TMLE", "Ctmle"),
    ("cui_selective_ml", "selective ML", "CuiSelectiveMl"),
    ("ma_dr_bc", "Ma DR-BC", "MaDrBc"),
)
PRIMARY_METHODS = (
    ("aipw", "AIPW", "Aipw"),
    ("ctmle", "C-TMLE", "Ctmle"),
    ("cui_selective_ml", "selective ML", "CuiSelectiveMl"),
    ("ma_dr_bc", "Ma DR-BC", "MaDrBc"),
)
FAMILIES = (
    ("primary", "primary datasets", "Primary"),
    ("all", "full matrix", "All"),
    ("kang_schafer", "Kang--Schafer", "KangSchafer"),
    ("alignment", "alignment stress", "Alignment"),
    ("real", "public covariates", "Real"),
    ("anchor", "aligned anchor", "Anchor"),
)
PRIMARY_DATASETS = (
    ("kang_schafer", "Kang--Schafer"),
    ("real", "public covariates"),
)
DIAGNOSTIC_FAMILIES = (
    ("alignment", "alignment stress"),
    ("anchor", "aligned anchor"),
)
COMMENT = "% Generated by scripts/assemble_section4_unified_global_residual.py; do not edit.\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--summary",
        type=Path,
        default=Path("support_csv/dml_unified_cartesian_global_residual_20260814/family_summary.csv"),
    )
    parser.add_argument("--cell-summary", type=Path)
    parser.add_argument("--out-dir", type=Path, required=True)
    return parser.parse_args()


def pct(value: str | float, digits: int = 3) -> str:
    return f"{100.0 * float(value):.{digits}f}"


def rate(value: str | float) -> str:
    return f"{100.0 * float(value):.1f}"


def read_rows(path: Path) -> dict[tuple[str, str], dict[str, str]]:
    with path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    keyed = {(row["method"], row["family"]): row for row in rows}
    expected = {(method, family) for method, _, _ in METHODS for family, _, _ in FAMILIES}
    observed = set(keyed)
    if expected != observed:
        missing = sorted(expected - observed)
        extra = sorted(observed - expected)
        raise SystemExit(f"summary keys differ: missing={missing}, extra={extra}")
    return keyed


def read_cell_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    expected_methods = {method for method, _, _ in METHODS}
    observed_methods = {row["method"] for row in rows}
    if observed_methods != expected_methods:
        raise SystemExit(
            f"setting summary methods differ: {sorted(observed_methods)}"
        )
    return rows


def write_values(path: Path, rows: dict[tuple[str, str], dict[str, str]]) -> None:
    lines = [COMMENT]
    for method, _, method_macro in METHODS:
        for family, _, family_macro in FAMILIES:
            row = rows[(method, family)]
            stem = f"SFourUnified{method_macro}{family_macro}"
            lines.extend(
                [
                    f"\\newcommand{{\\{stem}Settings}}{{{int(row['cells'])}}}\n",
                    f"\\newcommand{{\\{stem}Gain}}{{{pct(row['equal_cell_gain'])}}}\n",
                    f"\\newcommand{{\\{stem}Lo}}{{{pct(row['equal_cell_gain_ci_low'])}}}\n",
                    f"\\newcommand{{\\{stem}Hi}}{{{pct(row['equal_cell_gain_ci_high'])}}}\n",
                    f"\\newcommand{{\\{stem}Activation}}{{{rate(row['final_activation'])}}}\n",
                    f"\\newcommand{{\\{stem}Harm}}{{{rate(row['unconditional_harm'])}}}\n",
                ]
            )
    path.write_text("".join(lines))


def gain_cell(row: dict[str, str]) -> str:
    return (
        f"${pct(row['equal_cell_gain'])}\\%\\ "
        f"[{pct(row['equal_cell_gain_ci_low'])},{pct(row['equal_cell_gain_ci_high'])}]$"
    )


def write_overview(path: Path, rows: dict[tuple[str, str], dict[str, str]]) -> None:
    lines = [
        COMMENT,
        "\\begin{table}[t]\n",
        "\\centering\n",
        "\\small\n",
        "\\caption{Primary global-residual repair readout at the prespecified $c=2$. Each row averages the 20 primary dataset settings: eight Kang--Schafer settings and twelve public-covariate settings. Intervals are paired percentile-bootstrap intervals, stratified by dataset setting.}\n",
        "\\label{tab:unified-global-residual-overview}\n",
        "\\begin{tabular}{@{}lrrr@{}}\n",
        "\\toprule\n",
        "upstream estimator & settings & MSE gain (95\\% CI) & active / harm \\\\\n",
        "\\midrule\n",
    ]
    for method, label, _ in PRIMARY_METHODS:
        row = rows[(method, "primary")]
        lines.append(
            f"{label} & {int(row['cells'])} & {gain_cell(row)} & "
            f"{rate(row['final_activation'])}\\% / {rate(row['unconditional_harm'])}\\% \\\\\n"
        )
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n", "\\end{table}\n"])
    path.write_text("".join(lines))


def setting_label(row: dict[str, str]) -> str:
    design = row["design"]
    strength = float(row["strength"])
    if row["group"] == "kang_schafer":
        spec = design.replace("kang_schafer_", "").upper()
        return f"KS {spec}, $n={int(row['n'])}$"
    strength_label = str(int(strength)) if strength.is_integer() else str(strength)
    source = design.replace("real_", "").replace("_", " ")
    return f"{source}, $s={strength_label}$"


def write_family_table(path: Path, rows: list[dict[str, str]]) -> None:
    primary_rows = [
        row
        for row in rows
        if row["group"] in {"kang_schafer", "real"}
        and row["method"] in {method for method, _, _ in PRIMARY_METHODS}
    ]
    by_setting: dict[tuple[str, str, int, float], dict[str, dict[str, str]]] = {}
    for row in primary_rows:
        key = (row["group"], row["design"], int(row["n"]), float(row["strength"]))
        by_setting.setdefault(key, {})[row["method"]] = row
    missing = []
    for key, methods in by_setting.items():
        for method, _, _ in PRIMARY_METHODS:
            if method not in methods:
                missing.append((key, method))
    if missing:
        raise SystemExit(f"setting table missing methods: {missing[:5]}")
    ks_keys = sorted(
        [key for key in by_setting if key[0] == "kang_schafer"],
        key=lambda key: (key[1], key[2]),
    )
    real_keys = sorted(
        [key for key in by_setting if key[0] == "real"],
        key=lambda key: (key[1], key[3], key[2]),
    )
    lines = [
        COMMENT,
        "\\begin{table}[t]\n",
        "\\centering\n",
        "\\scriptsize\n",
        "\\caption{Setting-level primary readout for the global-residual repair. Entries are percent MSE gains at $c=2$; Table~\\ref{tab:unified-global-residual-overview} gives aggregate uncertainty. The fixed-floor TMLE diagnostic is omitted from this primary table.}\n",
        "\\label{tab:unified-global-residual-families}\n",
        "\\begin{tabular}{@{}lrrrr@{}}\n",
        "\\toprule\n",
        "setting & AIPW & C-TMLE & selective ML & Ma DR-BC \\\\\n",
        "\\midrule\n",
    ]
    for group_label, keys in (("Kang--Schafer", ks_keys), ("Public covariates", real_keys)):
        lines.append(
            f"\\multicolumn{{5}}{{@{{}}l}}{{\\textit{{{group_label}}}}} \\\\\n"
        )
        for key in keys:
            setting = setting_label(next(iter(by_setting[key].values())))
            values = [
                f"${pct(by_setting[key][method]['repaired_gain'])}$"
                for method, _, _ in PRIMARY_METHODS
            ]
            lines.append(f"{setting} & " + " & ".join(values) + " \\\\\n")
        if group_label != "Public covariates":
            lines.append("\\addlinespace\n")
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n", "\\end{table}\n"])
    path.write_text("".join(lines))


def write_synthetic_diagnostic_table(
    path: Path, rows: dict[tuple[str, str], dict[str, str]]
) -> None:
    lines = [
        COMMENT,
        "\\begin{table}[t]\n",
        "\\centering\n",
        "\\scriptsize\n",
        "\\caption{Synthetic support diagnostics for the global-residual repair. Alignment stress varies whether the defect lies in, partially overlaps, or misses the low-response region; aligned anchor repeats an aligned regional shift. These rows are not included in the primary dataset average.}\n",
        "\\label{tab:unified-global-residual-diagnostics}\n",
        "\\begin{tabular}{@{}llrr@{}}\n",
        "\\toprule\n",
        "diagnostic & upstream estimator & settings & MSE gain (95\\% CI) \\\\\n",
        "\\midrule\n",
    ]
    for family, family_label in DIAGNOSTIC_FAMILIES:
        for method, method_label, _ in PRIMARY_METHODS:
            row = rows[(method, family)]
            lines.append(
                f"{family_label} & {method_label} & {int(row['cells'])} & {gain_cell(row)} \\\\\n"
            )
        if family != DIAGNOSTIC_FAMILIES[-1][0]:
            lines.append("\\addlinespace\n")
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n", "\\end{table}\n"])
    path.write_text("".join(lines))


def write_tmle_diagnostic_table(
    path: Path, rows: dict[tuple[str, str], dict[str, str]]
) -> None:
    lines = [
        COMMENT,
        "\\begin{table}[t]\n",
        "\\centering\n",
        "\\small\n",
        "\\caption{Diagnostic fixed-floor TMLE readout for the global-residual run. The fixed-floor arm uses a nonadaptive propensity floor of 0.05 and is not the primary TMLE comparator.}\n",
        "\\label{tab:fixed-floor-tmle-diagnostic}\n",
        "\\begin{tabular}{@{}lrrr@{}}\n",
        "\\toprule\n",
        "family & settings & MSE gain (95\\% CI) & active / harm \\\\\n",
        "\\midrule\n",
    ]
    for family, family_label, _ in FAMILIES:
        row = rows[("tmle", family)]
        lines.append(
            f"{family_label} & {int(row['cells'])} & {gain_cell(row)} & "
            f"{rate(row['final_activation'])}\\% / {rate(row['unconditional_harm'])}\\% \\\\\n"
        )
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n", "\\end{table}\n"])
    path.write_text("".join(lines))


def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    rows = read_rows(args.summary)
    cell_rows = read_cell_rows(args.cell_summary or args.summary.with_name("cell_summary.csv"))
    write_values(args.out_dir / "section4_values.tex", rows)
    write_overview(args.out_dir / "section4_unified_overview_table.tex", rows)
    write_family_table(args.out_dir / "section4_unified_family_table.tex", cell_rows)
    write_synthetic_diagnostic_table(
        args.out_dir / "section4_synthetic_diagnostic_table.tex", rows
    )
    write_tmle_diagnostic_table(
        args.out_dir / "section4_fixed_floor_tmle_diagnostic_table.tex", rows
    )


if __name__ == "__main__":
    main()
