def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--low-run-dir",
        action="append",
        required=True,
        type=Path,
        help="Raw low-response run directory containing *.reps.csv.",
    )
    parser.add_argument(
        "--high-run-dir",
        action="append",
        required=True,
        type=Path,
        help="Raw high-response placebo run directory containing *.reps.csv.",
    )
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--draws", type=int, default=20_000)
    parser.add_argument("--seed", type=int, default=20260831)
    return parser.parse_args()


def as_float(value: str) -> float:
    try:
        return float(value)
    except ValueError:
        return math.nan


def mean(values) -> float:
    values = list(values)
    if not values:
        return math.nan
    return sum(values) / len(values)


def percentile(values: list[float], pct: float) -> float:
    ordered = sorted(values)
    position = (len(ordered) - 1) * pct / 100.0
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    weight = position - lower
    return ordered[lower] * (1.0 - weight) + ordered[upper] * weight


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(
                {
                    key: (
                        f"{value:.12g}"
                        if isinstance((value := row.get(key, "")), float)
                        else value
                    )
                    for key in fields
                }
            )


def design_setting(design: str, n: int, strength: float) -> tuple[str, str] | None:
    if design.startswith("kang_schafer_"):
        spec = design.replace("kang_schafer_", "").upper()
        return "Kang--Schafer", f"KS {spec}, $n={n}$"
    for _dataset_key, label, _raw_path, design_pairs in BENCHMARK_DATASETS:
        mapping = dict(design_pairs)
        if design in mapping and strength in {0.0, 3.0}:
            strength_label = str(int(strength))
            return "Semi-synthetic benchmarks", f"{label} {mapping[design]}, $s={strength_label}$"
    return None


def canonical_key(row: dict[str, str]) -> tuple[str, str, str, int, float] | None:
    method = row["reference_method"]
    if method not in PRIMARY_METHODS:
        return None
    design = row["design"]
    n = int(row["n"])
    strength = float(row["strength"])
    setting = design_setting(design, n, strength)
    if setting is None:
        return None
    group_label, setting_label = setting
    return group_label, setting_label, method, n, strength


def chunk_from_path(path: Path) -> int:
    match = re.search(r"_chunk(\d+)\.reps\.csv$", path.name)
    if not match:
        raise SystemExit(f"cannot parse chunk from {path}")
    return int(match.group(1))


def read_reps_dirs(paths: list[Path]) -> tuple[dict[tuple[str, str, str, int, float], list[dict[str, str]]], int, int]:
    grouped: dict[tuple[str, str, str, int, float], list[dict[str, str]]] = defaultdict(list)
    files = 0
    rows_seen = 0
    for run_dir in paths:
        for path in sorted(run_dir.glob("*.reps.csv")):
            chunk = chunk_from_path(path)
            with path.open(newline="") as handle:
                for row in csv.DictReader(handle):
                    key = canonical_key(row)
                    if key is None:
                        continue
                    row = dict(row)
                    row["pair_id"] = f"{key}|chunk={chunk}|rep={row['rep']}"
                    grouped[key].append(row)
                    rows_seen += 1
            files += 1
    return grouped, files, rows_seen


def metric(values: list[dict[str, str]], target_column: str) -> tuple[list[float], list[float]]:
    reference = [as_float(row["ref_error"]) ** 2 for row in values]
    target = [as_float(row[target_column]) ** 2 for row in values]
    return reference, target


def gain(reference: list[float], target: list[float]) -> float:
    ref_mse = mean(reference)
    if ref_mse <= 0.0:
        raise SystemExit("zero reference MSE encountered")
    return 1.0 - mean(target) / ref_mse


def paired_draws(
    low_rows: list[dict[str, str]],
    high_rows: list[dict[str, str]],
    rng: random.Random,
    draws: int,
) -> list[tuple[float, float, float]]:
    low_by_pair = {row["pair_id"]: row for row in low_rows}
    high_by_pair = {row["pair_id"]: row for row in high_rows}
    pair_ids = sorted(set(low_by_pair) & set(high_by_pair))
    if len(pair_ids) != min(len(low_rows), len(high_rows)):
        raise SystemExit(
            "low/high rows are not paired: "
            f"low={len(low_rows)} high={len(high_rows)} pairs={len(pair_ids)}"
        )
    low_ref = [as_float(low_by_pair[pair_id]["ref_error"]) ** 2 for pair_id in pair_ids]
    low_target = [
        as_float(low_by_pair[pair_id]["shrink_error"]) ** 2 for pair_id in pair_ids
    ]
    high_ref = [
        as_float(high_by_pair[pair_id]["ref_error"]) ** 2 for pair_id in pair_ids
    ]
    high_target = [
        as_float(high_by_pair[pair_id]["shrink_error"]) ** 2 for pair_id in pair_ids
    ]
    result = []
    for _ in range(draws):
        low_ref_total = 0.0
        low_target_total = 0.0
        high_ref_total = 0.0
        high_target_total = 0.0
        for _ in pair_ids:
            index = rng.randrange(len(pair_ids))
            low_ref_total += low_ref[index]
            low_target_total += low_target[index]
            high_ref_total += high_ref[index]
            high_target_total += high_target[index]
        low_gain = 1.0 - low_target_total / low_ref_total
        high_gain = 1.0 - high_target_total / high_ref_total
        result.append((low_gain, high_gain, low_gain - high_gain))
    return result


def summarize_setting(
    key: tuple[str, str, str, int, float],
    low_rows: list[dict[str, str]],
    high_rows: list[dict[str, str]],
    rng: random.Random,
    draws: int,
) -> tuple[dict[str, object], list[tuple[float, float, float]]]:
    low_ref, low_target = metric(low_rows, "shrink_error")
    high_ref, high_target = metric(high_rows, "shrink_error")
    boot = paired_draws(low_rows, high_rows, rng, draws)
    group_label, setting_label, method, n, strength = key
    return (
        {
            "group": group_label,
            "setting": setting_label,
            "method": method,
            "n": n,
            "strength": strength,
            "reps": len(low_rows),
            "low_response_gain": gain(low_ref, low_target),
            "low_response_gain_ci_low": percentile([draw[0] for draw in boot], 2.5),
            "low_response_gain_ci_high": percentile([draw[0] for draw in boot], 97.5),
            "high_response_gain": gain(high_ref, high_target),
            "high_response_gain_ci_low": percentile([draw[1] for draw in boot], 2.5),
            "high_response_gain_ci_high": percentile([draw[1] for draw in boot], 97.5),
            "low_minus_high_gain": gain(low_ref, low_target) - gain(high_ref, high_target),
            "low_minus_high_gain_ci_low": percentile([draw[2] for draw in boot], 2.5),
            "low_minus_high_gain_ci_high": percentile([draw[2] for draw in boot], 97.5),
            "low_final_activation": mean(
                1.0 if as_float(row["weight"]) > 0.0 else 0.0 for row in low_rows
            ),
            "high_final_activation": mean(
                1.0 if as_float(row["weight"]) > 0.0 else 0.0 for row in high_rows
            ),
            "low_harm": mean(
                1.0
                if as_float(row["shrink_error"]) ** 2 > as_float(row["ref_error"]) ** 2
                else 0.0
                for row in low_rows
            ),
            "high_harm": mean(
                1.0
                if as_float(row["shrink_error"]) ** 2 > as_float(row["ref_error"]) ** 2
                else 0.0
                for row in high_rows
            ),
        },
        boot,
    )


def summarize_method(
    method: str,
    rows: list[dict[str, object]],
    draws_by_setting: dict[tuple[str, str, str, int, float], list[tuple[float, float, float]]],
    draws: int,
) -> dict[str, object]:
    method_rows = [row for row in rows if row["method"] == method]
    if len(method_rows) != 24:
        raise SystemExit(f"{method}: expected 24 settings, found {len(method_rows)}")
    setting_keys = [
        (
            str(row["group"]),
            str(row["setting"]),
            str(row["method"]),
            int(row["n"]),
            float(row["strength"]),
        )
        for row in method_rows
    ]
    aggregate_draws = []
    for index in range(draws):
        low = mean(draws_by_setting[key][index][0] for key in setting_keys)
        high = mean(draws_by_setting[key][index][1] for key in setting_keys)
        diff = mean(draws_by_setting[key][index][2] for key in setting_keys)
        aggregate_draws.append((low, high, diff))
    return {
        "method": method,
        "settings": len(method_rows),
        "low_response_gain": mean(float(row["low_response_gain"]) for row in method_rows),
        "low_response_gain_ci_low": percentile([draw[0] for draw in aggregate_draws], 2.5),
        "low_response_gain_ci_high": percentile([draw[0] for draw in aggregate_draws], 97.5),
        "high_response_gain": mean(float(row["high_response_gain"]) for row in method_rows),
        "high_response_gain_ci_low": percentile([draw[1] for draw in aggregate_draws], 2.5),
        "high_response_gain_ci_high": percentile([draw[1] for draw in aggregate_draws], 97.5),
        "low_minus_high_gain": mean(float(row["low_minus_high_gain"]) for row in method_rows),
        "low_minus_high_gain_ci_low": percentile([draw[2] for draw in aggregate_draws], 2.5),
        "low_minus_high_gain_ci_high": percentile([draw[2] for draw in aggregate_draws], 97.5),
        "low_positive_settings": sum(float(row["low_response_gain"]) > 0.0 for row in method_rows),
        "high_positive_settings": sum(float(row["high_response_gain"]) > 0.0 for row in method_rows),
        "low_final_activation": mean(float(row["low_final_activation"]) for row in method_rows),
        "high_final_activation": mean(float(row["high_final_activation"]) for row in method_rows),
        "low_harm": mean(float(row["low_harm"]) for row in method_rows),
        "high_harm": mean(float(row["high_harm"]) for row in method_rows),
    }


def pct(value: float, digits: int = 3) -> str:
    rounded = round(100.0 * value, digits)
    if rounded == 0:
        rounded = 0.0
    return f"{rounded:.{digits}f}"


def table_value(row: dict[str, object], prefix: str) -> str:
    return (
        f"${pct(float(row[f'{prefix}_gain']))}\\%\\ "
        f"[{pct(float(row[f'{prefix}_gain_ci_low']))},"
        f"{pct(float(row[f'{prefix}_gain_ci_high']))}]$"
    )


def write_latex_table(path: Path, rows: list[dict[str, object]]) -> None:
    by_method = {str(row["method"]): row for row in rows}
    lines = [
        COMMENT,
        "\\begin{table}[t]\n",
        "\\centering\n",
        "\\small\n",
        "\\caption{High-response placebo ablation on the same 24 benchmark settings as Table~\\ref{tab:unified-global-residual-families}.  We compare a residual correction restricted to the low-response region with the same correction restricted to a matched high-response placebo region. Entries are equal-setting percent MSE gain with paired percentile intervals.}\n",
        "\\label{tab:high-response-placebo-ablation}\n",
        "\\begin{tabular}{@{}lrrr@{}}\n",
        "\\toprule\n",
        "expert family & low-response repair & high-response placebo & low minus high \\\\\n",
        "\\midrule\n",
    ]
    for method in PRIMARY_METHODS:
        row = by_method[method]
        lines.append(
            f"{METHOD_LABELS[method]} & "
            f"{table_value(row, 'low_response')} & "
            f"{table_value(row, 'high_response')} & "
            f"{table_value(row, 'low_minus_high')} \\\\\n"
        )
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n", "\\end{table}\n"])
    path.write_text("".join(lines))


def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    low_rows, low_files, low_raw_rows = read_reps_dirs(args.low_run_dir)
    high_rows, high_files, high_raw_rows = read_reps_dirs(args.high_run_dir)

    if set(low_rows) != set(high_rows):
        missing_high = sorted(set(low_rows) - set(high_rows))[:10]
        missing_low = sorted(set(high_rows) - set(low_rows))[:10]
        raise SystemExit(
            f"low/high setting keys differ: missing_high={missing_high} "
            f"missing_low={missing_low}"
        )
    if len(low_rows) != 24 * len(PRIMARY_METHODS):
        raise SystemExit(f"expected 96 low/high setting-expert groups, found {len(low_rows)}")

    rng = random.Random(args.seed)
    setting_rows: list[dict[str, object]] = []
    setting_draws: dict[tuple[str, str, str, int, float], list[tuple[float, float, float]]] = {}
    for key in sorted(low_rows):
        row, draws = summarize_setting(key, low_rows[key], high_rows[key], rng, args.draws)
        setting_rows.append(row)
        setting_draws[key] = draws

    summary_rows = [
        summarize_method(method, setting_rows, setting_draws, args.draws)
        for method in PRIMARY_METHODS
    ]
    setting_fields = [
        "group",
        "setting",
        "method",
        "n",
        "strength",
        "reps",
        "low_response_gain",
        "low_response_gain_ci_low",
        "low_response_gain_ci_high",
        "high_response_gain",
        "high_response_gain_ci_low",
        "high_response_gain_ci_high",
        "low_minus_high_gain",
        "low_minus_high_gain_ci_low",
        "low_minus_high_gain_ci_high",
        "low_final_activation",
        "high_final_activation",
        "low_harm",
        "high_harm",
    ]
    summary_fields = [
        "method",
        "settings",
        "low_response_gain",
        "low_response_gain_ci_low",
        "low_response_gain_ci_high",
        "high_response_gain",
        "high_response_gain_ci_low",
        "high_response_gain_ci_high",
        "low_minus_high_gain",
        "low_minus_high_gain_ci_low",
        "low_minus_high_gain_ci_high",
        "low_positive_settings",
        "high_positive_settings",
        "low_final_activation",
        "high_final_activation",
        "low_harm",
        "high_harm",
    ]
    write_csv(args.out_dir / "high_response_placebo_cell_summary.csv", setting_rows, setting_fields)
    write_csv(args.out_dir / "high_response_placebo_summary.csv", summary_rows, summary_fields)
    write_latex_table(
        args.out_dir / "section4_high_response_placebo_ablation_table.tex",
        summary_rows,
    )

    verification = {
        "status": "PASS",
        "draws": args.draws,
        "seed": args.seed,
        "settings": 24,
        "methods": list(PRIMARY_METHODS),
        "setting_expert_groups": len(setting_rows),
        "low_reps_files_read": low_files,
        "low_raw_replication_rows_read": low_raw_rows,
        "high_reps_files_read": high_files,
        "high_raw_replication_rows_read": high_raw_rows,
        "high_run_dirs": [str(path) for path in args.high_run_dir],
        "low_run_dirs": [str(path) for path in args.low_run_dir],
        "outputs": {
            name: sha256(args.out_dir / name)
            for name in (
                "high_response_placebo_cell_summary.csv",
                "high_response_placebo_summary.csv",
                "section4_high_response_placebo_ablation_table.tex",
            )
        },
    }
    (args.out_dir / "verification.json").write_text(
        json.dumps(verification, indent=2, sort_keys=True) + "\n"
    )


if __name__ == "__main__":
    main()
